Automatizacao= """ WITH LIDERANCAS AS (
    SELECT
        UPPER(TRIM(F.NOMFUN)) AS NOME_LIDERANCA,
        C.EMACOM AS EMAIL_LIDERANCA,

        ROW_NUMBER() OVER (
            PARTITION BY UPPER(TRIM(F.NOMFUN))
            ORDER BY
                CASE
                    WHEN TRIM(C.EMACOM) IS NOT NULL THEN 0
                    ELSE 1
                END,
                F.NUMEMP,
                F.NUMCAD
        ) AS RN

    FROM R034FUN F

    LEFT JOIN R034CPL C
        ON F.NUMEMP = C.NUMEMP
       AND F.TIPCOL = C.TIPCOL
       AND F.NUMCAD = C.NUMCAD
),

CONTRATOS_DETERMINADOS AS (
    SELECT
        N.NUMEMP,
        N.TIPCOL,
        N.NUMCAD,
        N.DATNOT AS DATA_ANOTACAO,
        N.SEQNOT AS SEQUENCIA,
        N.TIPNOT AS TIPO_ANOTACAO,
        N.NRODOC AS DOCUMENTO,
        N.NOTFIC AS DESCRICAO_COMPLETA,
        LENGTH(N.NOTFIC) AS TAMANHO_TEXTO,

        ROW_NUMBER() OVER (
            PARTITION BY
                N.NUMEMP,
                N.TIPCOL,
                N.NUMCAD
            ORDER BY
                N.DATNOT DESC,
                N.SEQNOT DESC
        ) AS RN

    FROM R038NOT N

    WHERE N.NUMEMP = 1
      AND N.TIPCOL = 1
      AND N.TIPNOT = 28
      AND N.DATNOT >= DATE '2026-01-01'
      
)

SELECT
    F.DATADM AS "Admissão",

    F.NUMCAD AS "Crachá",

    F.NOMFUN AS "Colaborador",

    CAR.TITCAR AS "Cargo",

    SIT.DESSIT AS "Situação",

    F.CODCCU AS "Centro de Custo",

    CC.NOMCCU AS "Descrição do Centro de Custo",

    TRIM(F.USU_CHEFIA) AS "Liderança",

    L.EMAIL_LIDERANCA AS "Email da Liderança",

    F.CODFIL AS "Filial",

    CD.DATA_ANOTACAO AS "Data Anotação",

    CD.SEQUENCIA AS "Sequência",

    CD.TIPO_ANOTACAO AS "Tipo Anotação",

    CD.DOCUMENTO AS "Documento",

    CD.DESCRICAO_COMPLETA AS "Descrição Completa",

    CD.TAMANHO_TEXTO AS "Tamanho Texto"

FROM CONTRATOS_DETERMINADOS CD

INNER JOIN R034FUN F
    ON F.NUMEMP = CD.NUMEMP
   AND F.TIPCOL = CD.TIPCOL
   AND F.NUMCAD = CD.NUMCAD

LEFT JOIN R024CAR CAR
    ON CAR.ESTCAR = F.ESTCAR
   AND CAR.CODCAR = F.CODCAR

LEFT JOIN R010SIT SIT
    ON SIT.CODSIT = F.SITAFA

LEFT JOIN R018CCU CC
    ON CC.NUMEMP = F.NUMEMP
   AND CC.CODCCU = F.CODCCU

LEFT JOIN LIDERANCAS L
    ON UPPER(TRIM(F.USU_CHEFIA)) = L.NOME_LIDERANCA
   AND L.RN = 1

WHERE CD.RN = 1

ORDER BY
    F.NOMFUN
"""

Gestantes= """ 
SELECT
    F.NUMEMP AS EMPRESA,
    F.NUMCAD AS CRACHA,
    F.NOMFUN AS COLABORADOR,
    E.CODETB AS CODIGO_ESTABILIDADE,
    E.INIETB AS INICIO_ESTABILIDADE,
    E.FIMETB AS FIM_ESTABILIDADE,
    E.STAATU AS STATUS,
    E.OBSINI AS OBSERVACAO_INICIAL,
    E.OBSFIM AS OBSERVACAO_FINAL

FROM APL_VETORH.R038HEB E

INNER JOIN APL_VETORH.R034FUN F
    ON E.NUMEMP = F.NUMEMP
   AND E.TIPCOL = F.TIPCOL
   AND E.NUMCAD = F.NUMCAD

WHERE E.CODETB = 32
AND E.INIETB <= TRUNC(SYSDATE)
AND E.FIMETB >= TRUNC(SYSDATE)


ORDER BY F.NOMFUN
"""